// ─── CREATE LOG MODAL ────────────────────────────────────────────────
const CreateLogModal: React.FC<{
  clients: any[];
  employees: any[];
  profile: any;
  user: any;
  onClose: () => void;
}> = ({ clients, employees, profile, user, onClose }) => {
  const [clientName, setClientName] = useState(clients[0]?.clientName || clients[0]?.name || '');
  const [employeeId, setEmployeeId] = useState(profile?.role === 'employee' ? (user?.uid || '') : (employees[0]?.userId || employees[0]?.id || user?.uid || ''));
  const [workDone, setWorkDone] = useState('');
  const [category, setCategory] = useState('Graphic Design');
  const [hours, setHours] = useState('');
  const [quantity, setQuantity] = useState('1');
  const [date, setDate] = useState(new Date().toISOString().split('T')[0]);
  const [workDetails, setWorkDetails] = useState('');
  const [saving, setSaving] = useState(false);

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    const desc = workDone.trim();
    if (!desc) return;

    const qty = parseInt(quantity, 10);
    if (isNaN(qty) || qty < 1) return;

    setSaving(true);
    try {
      const selectedEmp = employees.find(e => (e.userId || e.id) === employeeId);
      const selectedClient = clients.find(c => (c.clientName || c.name || c.businessName) === clientName);

      const empId = employeeId || user?.uid || '';
      const empName = selectedEmp?.name || profile?.name || 'Team Member';
      const cId = selectedClient?.id || selectedClient?.clientId || '';
      const cName = clientName || selectedClient?.clientName || selectedClient?.name || 'General Client';
      const parsedHours = hours ? parseFloat(hours) : null;
      const nowIso = new Date().toISOString();
      const logId = `worklog_manual_${Date.now()}`;

      // Build pure Work Log payload (source: 'manual', taskId: null, NO phantom task created)
      const logWithId: any = {
        id: logId,
        workLogId: logId,
        task_id: null,
        taskId: null,
        client_id: cId,
        client_name: cName,
        clientId: cId,
        clientName: cName,
        employee_id: empId,
        employee_name: empName,
        employeeId: empId,
        employeeName: empName,
        work_description: desc,
        workDone: desc,
        description: desc,
        task_type: category,
        category,
        quantity: qty,
        hours: parsedHours ?? null,
        workDetails: workDetails.trim(),
        work_details: workDetails.trim(),
        work_date: date,
        workDate: date,
        date,
        completed_at: nowIso,
        completedAt: nowIso,
        created_at: nowIso,
        createdAt: nowIso,
        updated_at: nowIso,
        updatedAt: nowIso,
        source: 'manual',
        auto_generated: false,
        autoGenerated: false,
        status: 'completed',
      };

      const sanitized = sanitizeFirestorePayload(logWithId);

      // 1. Update local storage cache immediately
      try {
        const cached = getCachedWorkLogs();
        const updated = [logWithId, ...cached.filter((l: any) => l.id !== logId)];
        localStorage.setItem('digi_persisted_worklogs_v2', JSON.stringify(updated));
      } catch (e) {}

      // 2. Dispatch global events
      window.dispatchEvent(new CustomEvent('worklogs_updated', { detail: logWithId }));
      window.dispatchEvent(new Event('worklogs_updated'));

      // 3. Persist to Firestore
      try {
        await setDoc(doc(db, 'workLogs', logId), sanitized, { merge: true });
        await addDoc(collection(db, 'activityLogs'), {
          userId: user?.uid || '',
          userName: profile?.name || 'Team Member',
          action: `manually logged work: ${desc}`,
          details: `${cName} (${category})`,
          createdAt: nowIso,
        });
      } catch (firestoreErr) {
        console.warn('WorkLog Firestore write notice (cached locally):', firestoreErr);
      }

      onClose();
    } catch (err) {
      console.error('Save log error:', err);
    } finally {
      setSaving(false);
    }
  };

  return (
    <div className="fixed inset-0 bg-black/60 backdrop-blur-xs flex items-center justify-center p-4 z-50 animate-in fade-in-50">
      <div className="bg-white dark:bg-[#111728] border border-[#D7DEE9] dark:border-[#293248] rounded-2xl p-6 max-w-lg w-full shadow-2xl space-y-4 animate-in zoom-in-95">
        <div className="flex items-center justify-between border-b border-[#D7DEE9] dark:border-[#293248] pb-3">
          <div className="flex items-center gap-2.5">
            <div className="w-8 h-8 rounded-xl bg-[#EEECFF] dark:bg-[#201D45] text-[#5B4BFF] dark:text-[#806CFF] flex items-center justify-center">
              <Plus className="w-4 h-4" />
            </div>
            <div>
              <h3 className="text-base font-black text-[#101828] dark:text-[#F7F8FC]">
                Log Manual Agency Work
              </h3>
              <p className="text-[11px] text-[#7A8496] dark:text-[#828BA1]">For work done outside scheduled board tasks</p>
            </div>
          </div>
          <button onClick={onClose} className="p-1 rounded-lg text-[#7A8496] hover:text-[#101828] dark:hover:text-white cursor-pointer">
            <X className="w-4 h-4" />
          </button>
        </div>

        <form onSubmit={handleSubmit} className="space-y-3.5 text-xs">
          <div>
            <label className="block text-[11px] font-bold text-[#101828] dark:text-[#F7F8FC] mb-1">
              Work Done / Deliverable Title *
            </label>
            <input
              type="text"
              required
              value={workDone}
              onChange={e => setWorkDone(e.target.value)}
              placeholder="e.g. Designed 3 Instagram story flyers for Monsoon Promo"
              className={inputCls}
            />
          </div>

          <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
            <div>
              <label className="block text-[11px] font-bold text-[#101828] dark:text-[#F7F8FC] mb-1">
                Client / Brand *
              </label>
              <select
                value={clientName}
                onChange={e => setClientName(e.target.value)}
                className={inputCls}
              >
                {clients.map(c => {
                  const name = c.clientName || c.name || c.businessName || 'Client';
                  return <option key={c.id || c.clientId} value={name}>{name}</option>;
                })}
              </select>
            </div>

            <div>
              <label className="block text-[11px] font-bold text-[#101828] dark:text-[#F7F8FC] mb-1">
                Work Category
              </label>
              <select
                value={category}
                onChange={e => setCategory(e.target.value)}
                className={inputCls}
              >
                {CATEGORIES.map(c => <option key={c} value={c}>{c}</option>)}
              </select>
            </div>
          </div>

          <div className="grid grid-cols-3 gap-2.5">
            <div>
              <label className="block text-[11px] font-bold text-[#101828] dark:text-[#F7F8FC] mb-1">
                Date
              </label>
              <input
                type="date"
                required
                value={date}
                onChange={e => setDate(e.target.value)}
                className={inputCls}
              />
            </div>
            <div>
              <label className="block text-[11px] font-bold text-[#101828] dark:text-[#F7F8FC] mb-1">
                Hours (Opt)
              </label>
              <input
                type="number"
                step="0.5"
                min="0"
                value={hours}
                onChange={e => setHours(e.target.value)}
                placeholder="e.g. 2.5"
                className={inputCls}
              />
            </div>
            <div>
              <label className="block text-[11px] font-bold text-[#101828] dark:text-[#F7F8FC] mb-1">
                Quantity
              </label>
              <input
                type="number"
                min="1"
                value={quantity}
                onChange={e => setQuantity(e.target.value)}
                className={inputCls}
              />
            </div>
          </div>

          <div>
            <label className="block text-[11px] font-bold text-[#101828] dark:text-[#F7F8FC] mb-1">
              Deliverable Notes / Drive Link (Optional)
            </label>
            <textarea
              rows={2}
              value={workDetails}
              onChange={e => setWorkDetails(e.target.value)}
              placeholder="Paste Google Drive asset link, revisions, or proof notes..."
              className={inputCls}
            />
          </div>

          <div className="flex items-center justify-end gap-2 pt-2 border-t border-[#D7DEE9] dark:border-[#293248]">
            <button
              type="button"
              onClick={onClose}
              className="px-3.5 py-2 rounded-xl text-xs font-bold text-[#475467] dark:text-[#BAC1D1] hover:bg-[#EEF1F6] dark:hover:bg-[#171E31] cursor-pointer"
            >
              Cancel
            </button>
            <button
              type="submit"
              disabled={saving}
              className="px-4 py-2 rounded-xl text-xs font-black uppercase tracking-wider text-white bg-[#5B4BFF] hover:bg-[#4E3FE6] dark:bg-[#806CFF] dark:hover:bg-[#725DEF] flex items-center gap-1.5 shadow-xs disabled:opacity-50 cursor-pointer"
            >
              {saving ? <Loader2 className="w-3.5 h-3.5 animate-spin" /> : <Check className="w-3.5 h-3.5" />}
              <span>Save Work Log</span>
            </button>
          </div>
        </form>
      </div>
    </div>
  );
};
