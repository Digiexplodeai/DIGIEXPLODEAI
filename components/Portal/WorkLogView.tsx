export const normalizeWorkLog = (d: any, id: string): WorkLog => {
  const data = typeof d === 'object' && d ? d : {};
  const taskId = data.task_id || data.taskId || undefined;
  const clientId = data.client_id || data.clientId || '';
  const clientName = data.client_name || data.clientName || 'General Client';
  const employeeId = data.employee_id || data.employeeId || '';
  const employeeName = data.employee_name || data.employeeName || 'Team Member';
  const workDone = data.work_description || data.workDone || data.title || 'Completed deliverable';
  const category = data.task_type || data.category || 'General';
  const quantity = data.quantity !== undefined ? Number(data.quantity) : 1;
  const source = data.source || (taskId || data.auto_generated || data.autoGenerated ? 'task_completion' : 'manual');
  
  // Format date robustly (handles YYYY-MM-DD, ISO strings, and Firestore Timestamp)
  let dateStr = '';
  if (data.work_date && typeof data.work_date === 'string') {
    dateStr = data.work_date.slice(0, 10);
  } else if (data.date && typeof data.date === 'string') {
    dateStr = data.date.slice(0, 10);
  } else if (data.completed_at && typeof data.completed_at === 'string') {
    dateStr = data.completed_at.slice(0, 10);
  } else if (data.completedAt && typeof data.completedAt === 'string') {
    dateStr = data.completedAt.slice(0, 10);
  } else if (data.created_at && typeof data.created_at === 'string') {
    dateStr = data.created_at.slice(0, 10);
  } else if (data.createdAt && typeof data.createdAt === 'string') {
    dateStr = data.createdAt.slice(0, 10);
  } else if (data.work_date?.toDate) {
    dateStr = data.work_date.toDate().toISOString().slice(0, 10);
  } else if (data.date?.toDate) {
    dateStr = data.date.toDate().toISOString().slice(0, 10);
  } else {
    dateStr = new Date().toISOString().slice(0, 10);
  }

  return {
    id: id || data.id || `log_${Date.now()}`,
    taskId,
    task_id: taskId,
    clientId,
    client_id: clientId,
    clientName,
    client_name: clientName,
    employeeId,
    employee_id: employeeId,
    employeeName,
    employee_name: employeeName,
    workDone,
    work_description: workDone,
    category,
    task_type: category,
    hours: data.hours !== undefined ? Number(data.hours) : undefined,
    quantity,
    workDetails: data.work_details || data.workDetails || '',
    source,
    auto_generated: source === 'task_completion',
    autoGenerated: source === 'task_completion',
    status: data.status || 'completed',
    date: dateStr,
    work_date: dateStr,
    completedAt: data.completed_at || data.completedAt || new Date().toISOString(),
    completed_at: data.completed_at || data.completedAt || new Date().toISOString(),
    createdAt: data.created_at || data.createdAt || new Date().toISOString(),
    created_at: data.created_at || data.createdAt || new Date().toISOString(),
    updatedAt: data.updated_at || data.updatedAt || new Date().toISOString(),
    video_production_id: data.video_production_id || data.videoProductionId || data.videoTrackerId || undefined,
    videoProductionId: data.video_production_id || data.videoProductionId || data.videoTrackerId || undefined,
  };
};

